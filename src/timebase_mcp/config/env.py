import os

DXAPI_SSL_TERMINATION_ENV = "DXAPI_SSL_TERMINATION"
DXAPI_SSL_TRUST_ALL_ENV = "DXAPI_SSL_TRUST_ALL"


def env_true(name: str) -> bool:
    return os.environ.get(name, "").casefold() == "true"


def dxapi_ssl_termination_enabled() -> bool:
    return env_true(DXAPI_SSL_TERMINATION_ENV)


def dxapi_ssl_trust_all_enabled() -> bool:
    return env_true(DXAPI_SSL_TRUST_ALL_ENV)


